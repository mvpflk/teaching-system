    a.excerpt = CONCAT(LEFT(COALESCE(n.content, ''), 200), CASE WHEN CHAR_LENGTH(COALESCE(n.content, '')) > 200 THEN '...' ELSE '' END),
    a.updated_at = NOW()
WHERE n.subject_id = @yy_zg_sid
  AND n.level = 4
  AND n.content IS NOT NULL
  AND n.content != '';


