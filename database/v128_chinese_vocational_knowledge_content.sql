'## 病句辨析与修辞\n\n'
'【一句话定义】\n考查学生识别六种常见病句类型的能力，以及辨析八种常见修辞手法及其表达效果的能力。\n\n'
'【具体说明】\n'
'**六种病句类型**：\n'
'① 语序不当：多层定语或状语次序错乱（"一位优秀的有20年教学经验的女教师"正确顺序为：领属+数量+性状+属性）、关联词位置不当（"不仅…而且…"前后主语一致时关联词放主语后）\n'
'② 搭配不当：主谓不当（"他的写作水平有了明显增长"→"提高"）、动宾不当（"我们要养成讲卫生"缺宾语→加上"的习惯"）、主宾不当（"北京的秋天是最美的季节"主语"秋天"与宾语"季节"不一致）、一面两面（"成败取决于努力"→"成功取决于努力"或"成败取决于努力与否"）\n'
'③ 成分残缺或赘余：缺主语（"通过这次学习，使我提高了认识"→去掉"通过"或"使"）、缺宾语（"我们要响应学校号召"完整，但"我们要积极响应"就缺宾语）、重复啰嗦（"目前的当务之急"→"当务之急"已含"目前"）\n'
'④ 结构混乱：句式杂糅（"本着…为原则"兼顾"本着…的原则"和"以…为原则"）、中途易辙（一句话未说完又接另一句）\n'
'⑤ 表意不明（歧义）：多义词歧义（"他走了一个多小时"的"走"可理解为行走或离开）、结构歧义（"咬死了猎人的狗"可有两种切分）、指代不明（"小明和小刚一起玩，他的书包掉了"→谁的书包？）\n'
'⑥ 不合逻辑：自相矛盾（"整个大楼一片漆黑，只有一个房间亮着灯"）、否定不当（"我们一定要避免不发生事故"逻辑是"发生事故"）、主客颠倒（"考试对我很熟悉"→"我对考试很熟悉"）、分类不当（"我们买了苹果、香蕉和水果"）\n\n'
'**八种修辞手法**：\n'
'① 比喻：明喻（像/如/仿佛）、暗喻（是/成了）、借喻（只出现喻体）\n'
'② 拟人：赋予事物人的特征（"太阳露出了笑脸"）\n'
'③ 夸张：扩大夸张（"飞流直下三千尺"）、缩小夸张（"五岭逶迤腾细浪"）、超前夸张\n'
'④ 排比：三个或以上结构相同或相似的语句，增强语势\n'
'⑤ 对偶：字数相等、结构相同、意义相关的两个语句（"海内存知己，天涯若比邻"）\n'
'⑥ 反复：连续反复或间隔反复相同词语，突出强调\n'
'⑦ 设问：自问自答，引起注意和思考；反问：答案在问句中，加强语气\n'
'⑧ 借代：以特征代本体（"红领巾"代少先队员）、以部分代整体（"帆"代船）\n\n'
'【常见错误】\n'
'1. 病句辨析凭语感 → 必须用"主干提取法"先找主谓宾，再分析枝叶\n'
'2. "两面词"陷阱 → 句中出现了"是否/能否/成败/好坏"，前后必须都对应两面\n'
'3. 修辞手法混淆 → 比喻vs比拟（比喻有本体喻体，比拟赋予人的特征）、借代vs借喻（借代是相关代替，借喻是相似比喻）\n\n'
'【考试方向】\n'
'病句：选择题"下列各句中没有语病的一项是"或"下列各句中有语病的一项是"。\n修辞：选择题"下列句子使用的修辞手法与其他三项不同的是"或"对下列句子修辞手法判断正确的一项是"。'
