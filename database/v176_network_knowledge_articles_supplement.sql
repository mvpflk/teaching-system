```
输出中的"工作站域"就是当前工作组名称。

## 实操二：文件共享设置

工作组中共享文件的核心是设置**共享文件夹**。

### 开启网络发现和文件共享

```cmd
控制面板 → 网络和共享中心 → 高级共享设置 →
  ✅ 启用网络发现
  ✅ 启用文件和打印机共享
```

> 如果网络类型是"公用网络"，需要先切换到"专用网络"才能启用网络发现。

### 共享文件夹步骤

| 步骤 | 操作 |
|:----:|:------|
| ① | 右键要共享的文件夹 → 「属性」 |
| ② | 切换到「共享」选项卡 → 点击「共享」按钮 |
| ③ | 在弹出的窗口中选择要共享的用户（Everyone=所有人） |
| ④ | 设置权限级别：读取（只能看）或读取/写入（可修改） |
| ⑤ | 点击「共享」→ 完成 |

### 在共享文件夹上放文件

```
共享后其他电脑可通过网络访问此文件夹，
路径格式: \\计算机名\共享文件夹名
如: \\PC-01\课件
```

## 实操三：访问共享文件

### 方法1：网络邻居
```
打开文件资源管理器 → 左侧点击「网络」→
双击目标计算机 → 双击共享文件夹
```

### 方法2：直接输入路径
```
按 Win+R 打开运行 → 输入 \\目标电脑名\共享名
例如: \\STUDENT-PC-05\课件
```

### 方法3：映射网络驱动器（常用）
```
右键「网络」中的共享文件夹 → 「映射网络驱动器」
→ 选择驱动器号（如 Z:）→ 完成
```
之后在文件管理器中直接访问 Z: 盘即可。

