|:----:|:-----|:----:|:-----|
| **∈** | 属于 | 元素在集合中 | 1∈{1,2,3} |
| **∉** | 不属于 | 元素不在集合中 | 4∉{1,2,3} |

## 常用数集

| 符号 | 名称 | 范围 |
|:----:|:-----|:-----|
| **N** | 自然数集 | {0,1,2,3,...} |
| **N*或Z⁺** | 正整数集 | {1,2,3,...} |
| **Z** | 整数集 | {...,-2,-1,0,1,2,...} |
| **Q** | 有理数集 | 所有分数和整数 |
| **R** | 实数集 | 有理数+无理数 |

## 典型例题

**例1**：判断 0 与 {0} 的关系。

0 是一个元素，{0} 是含有一个元素0的集合

所以 **0 ∈ {0}**（元素属于集合）

**例2**：若 {a, a², a+a²} 有三个元素，求a的范围。

三个元素互不相同：

① a ≠ a² → a ≠ 0 且 a ≠ 1

② a ≠ a+a² → a² ≠ 0 → a ≠ 0

③ a² ≠ a+a² → a ≠ 0

综合：**a ≠ 0 且 a ≠ 1**

**例3**：用列举法表示方程 x²-5x+6=0 的解集。

x²-5x+6=(x-2)(x-3)=0 → x=2 或 x=3

解集 = **{2, 3}**

