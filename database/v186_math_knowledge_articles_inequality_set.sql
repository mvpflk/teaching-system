**"大于取两边，小于取中间"**

- a(x-x₁)(x-x₂) > 0（a>0）的解集：**x < x₁ 或 x > x₂**（两根之外）
- a(x-x₁)(x-x₂) < 0（a>0）的解集：**x₁ < x < x₂**（两根之间）

