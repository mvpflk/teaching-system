## 各形式详解

### 点斜式

**y - y₀ = k(x - x₀)**

已知一点(x₀,y₀)和斜率k，直接代入。

**例**：过点(2,3)，斜率为4的直线：y-3=4(x-2)

### 斜截式

**y = kx + b**

k为斜率，b为y轴截距（直线与y轴交点的纵坐标）。

**例**：斜率为-2，过点(0,5)的直线：y=-2x+5

### 两点式

**(y-y₁)/(y₂-y₁) = (x-x₁)/(x₂-x₁)**

已知两点(x₁,y₁)和(x₂,y₂)。

**例**：过(1,2)和(3,6)的直线：(y-2)/(6-2)=(x-1)/(3-1) → y=2x

### 截距式

**x/a + y/b = 1**

a为x轴截距（与x轴交点横坐标），b为y轴截距。

**例**：过(3,0)和(0,4)的直线：x/3+y/4=1

