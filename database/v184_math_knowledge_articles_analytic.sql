## 斜率

斜率k表示直线的倾斜程度：**k = tanα**（α≠90°）

### 斜率公式

过两点 P₁(x₁,y₁) 和 P₂(x₂,y₂) 的直线斜率：

**k = (y₂-y₁)/(x₂-x₁)**（x₁≠x₂）

> 口诀："纵差除以横差"

### 斜率与倾斜角的关系

| 斜率k | 倾斜角α | 直线走向 |
|:-----:|:-------:|:--------:|
| k > 0 | α为锐角 | 从左到右**上升** |
| k < 0 | α为钝角 | 从左到右**下降** |
| k = 0 | α = 0° | **水平**线 |
| 不存在 | α = 90° | **竖直**线 |

### |k|与陡峭程度

|k|越大，直线越陡。

## 典型例题

**例1**：求过点A(1,2)和B(3,6)的直线斜率。

