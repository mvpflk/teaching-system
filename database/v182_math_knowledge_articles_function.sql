## 分段函数（重点）

分段函数是在**不同区间**用**不同解析式**表示的函数。

**经典例子——出租车计费**：

$$f(x) = \\begin{cases} 10, & 0 < x \\leq 3 \\\\ 10 + 2(x-3), & x > 3 \\end{cases}$$

**读法**：3公里以内10元，超过3公里每公里加收2元。

**注意**：分段函数是一个函数，不是多个函数！定义域是各段区间的并集。

