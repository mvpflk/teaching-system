函数的值域是函数值 y=f(x) 的**全体构成的集合**，即 {y | y=f(x), x∈定义域}。

## 五种常用求法

### 方法1：观察法

直接通过解析式判断 y 的取值范围。

**例**：f(x)=x²，因为 x²≥0，所以值域为 **[0,+∞)**。

**例**：f(x)=1/(x²+1)，因为 x²+1≥1，所以 0<f(x)≤1，值域为 **(0,1]**。

### 方法2：配方法（二次函数专用）

将二次函数配方，根据开口方向和顶点确定值域。

**例**：求 f(x)=-x²+2x+3 的值域。

配方：f(x)=-(x²-2x)+3=-(x-1)²+4

因为 -(x-1)²≤0，所以 f(x)≤4，值域为 **(-∞,4]**。

### 方法3：分离常数法（分式函数）

适用于 y=(ax+b)/(cx+d) 型（c≠0）。

**例**：求 f(x)=(2x+1)/(x-1) 的值域。

分离：f(x)=(2(x-1)+3)/(x-1)=2+3/(x-1)

因为 3/(x-1)≠0，所以 f(x)≠2，值域为 **(-∞,2)∪(2,+∞)**。

### 方法4：换元法

令 t=g(x)，将原函数转化为关于 t 的简单函数。

**例**：求 f(x)=x+√(x-1) 的值域。

令 t=√(x-1)（t≥0），则 x=t²+1

f(t)=t²+1+t=t²+t+1=(t+1/2)²+3/4

因为 t≥0，t+1/2≥1/2，所以 f(t)≥(1/2)²+3/4=1

值域为 **[1,+∞)**。

### 方法5：利用单调性

先判断单调性，再代端点求值域。

**例**：f(x)=2x+1 在 [0,3] 上单调递增。

最小值 f(0)=1，最大值 f(3)=7，值域为 **[1,7]**。

