'## 什么是函数？

函数是两个非空数集之间的一种**确定的对应关系**：对于集合A中的每一个x，按照某种对应法则f，都有**唯一确定**的y与之对应，记作 y=f(x)。

## 函数三要素

| 要素 | 含义 | 举例 |
|:----:|:-----|:-----|
| **定义域** | 自变量x的取值范围 | f(x)=1/x 的定义域为 x≠0 |
| **对应法则** | f的具体表达式 | f(x)=2x+1 |
| **值域** | 函数值y的全体 | f(x)=x² 的值域为 [0,+∞) |

> 三要素中只要有一个不同，就是不同的函数。

## 求定义域的核心规则

**必须同时满足以下所有条件：**

| 类型 | 条件 | 示例 |
|:----:|:----:|:-----|
| 分式 | 分母 ≠ 0 | f(x)=1/(x-2) → x≠2 |
| 偶次根号 | 被开方数 ≥ 0 | f(x)=√(x+1) → x≥-1 |
| 对数 | 真数 > 0 | f(x)=lg(x-3) → x>3 |
| 零指数 | 底数 ≠ 0 | f(x)=(x-1)⁰ → x≠1 |

## 复合函数定义域

若 f(x) 的定义域为 [a,b]，求 f(g(x)) 的定义域：

**核心思路**：g(x) 的取值范围必须落在 [a,b] 内。

**例**：f(x) 的定义域为 [0,4]，求 f(x²) 的定义域。

解：令 0 ≤ x² ≤ 4，即 x² ≤ 4 → -2 ≤ x ≤ 2。所以 f(x²) 的定义域为 [-2,2]。

## 常见题型

### 题型1：求具体函数定义域

**例**：求 f(x) = √(x-1) + 1/(x-3) 的定义域。

解：x-1 ≥ 0 且 x-3 ≠ 0 → x ≥ 1 且 x ≠ 3 → **[1,3) ∪ (3,+∞)**

### 题型2：已知 f(x) 定义域求 f(g(x)) 定义域

**例**：f(x) 的定义域为 [-1,2]，求 f(2x+1) 的定义域。

解：-1 ≤ 2x+1 ≤ 2 → -2 ≤ 2x ≤ 1 → **-1 ≤ x ≤ 1/2**

### 题型3：求实际问题的定义域

**例**：一个长方形的周长为20，设一边长为x，面积为S=x(10-x)。求S的定义域。

解：x > 0 且 10-x > 0 → **0 < x < 10**

