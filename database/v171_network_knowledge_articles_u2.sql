'## 什么是局域网？

局域网（Local Area Network，LAN）是将**较小地理范围**内的计算机和通信设备互连起来的网络。

### 一句话理解
> 局域网就像一个单位内部的"小网络"——一个办公室、一栋楼、一个校园内。

## 局域网的基本组成

| 组成部分 | 具体内容 | 典型例子 |
|---------|---------|---------|
| **硬件设备** | 计算机、网卡、传输介质 | PC、NIC、双绞线 |
| **网络设备** | 连接和转发数据的中介设备 | 交换机、集线器 |
