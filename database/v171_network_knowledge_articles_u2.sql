### 2.4GHz vs 5GHz

| 频段 | 覆盖范围 | 穿墙能力 | 速度 | 干扰 |
|:----:|:--------:|:--------:|:----:|:----:|
| **2.4GHz** | 远 | 好 | 慢 | 多（蓝牙/微波炉干扰）|
| **5GHz** | 近 | 差 | 快 | 少 |

> **现在的路由器大多是双频的**——支持2.4GHz和5GHz同时工作。

## WLAN的组成

| 设备 | 作用 | 类比 |
|:----:|:----:|:----:|
| **无线网卡** | 计算机端的无线收发设备 | 有线网卡的无线版 |
| **AP（Access Point）** | 无线接入点，连接有线/无线网络 | 无线信号的"基站" |
| **无线路由器** | AP+路由器+交换机三合一 | 家庭网络的核心 |

### 家庭常见的连接方式
```
Internet → 光猫 → 无线路由器 → 无线连接手机/电脑/电视
                            → 有线连接台式机/打印机
```

