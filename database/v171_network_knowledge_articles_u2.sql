### 点分十进制表示法

将32位二进制分成4组，每组8位（1字节），分别转换为十进制，用`.`连接：

```
二进制: 11000000 10101000 00000001 00001010
               ↓        ↓        ↓        ↓
十进制:    192   .  168   .   1    .   10
               → 192.168.1.10
```

### 每段范围

每段8位二进制 → 十进制范围 **0~255**

| 二进制 | 十进制 |
|:------:|:------:|
| 00000000 | 0 |
| 00000001 | 1 |
| ... | ... |
| 11111110 | 254 |
| 11111111 | 255 |

> 结论：**IP地址中任何一段都不会超过255**，这是判断题常见陷阱。

