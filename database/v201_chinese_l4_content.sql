'## 关联词语搭配

【一句话定义】
关联词语是连接分句表达逻辑关系的词语，高考考查其固定搭配和逻辑关系对应是否准确。

【核心要点】
- 并列关系：既...又...、一边...一边...、不是...而是...（否定肯定并列）。
- 递进关系：不但(不仅)...而且(还)...、甚至、尚且...何况...。
- 选择关系：或者...或者...、不是...就是...（二者必居其一）、宁可...也不...。
- 转折关系：虽然...但是...、尽管...可是...、然而（"尽管"后接事实，"即使"后接假设，易混淆）。
- 因果关系：因为...所以...、既然...就...（已知原因推结果）。
- 条件关系：只有...才...（必要条件）、只要...就...（充分条件）、无论...都...（无条件）。
- 假设关系：如果...就...、即使(纵然)...也...（"即使"表假设让步）。

【记忆技巧】
成对记忆法：关联词大多成对使用，"不但"配"而且"，"只有"配"才"，"只要"配"就"。"即使/尽管"对比法："即使"表假设（还没发生），"尽管"表事实（已发生）。"只有/只要"区分法："只有...才..."强调唯一条件；"只要...就..."强调条件充分。

