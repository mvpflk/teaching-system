'## 什么是网络拓扑结构？

网络拓扑结构是指网络中计算机和通信设备的**物理连接方式**（布局形态）。不同拓扑结构影响网络的性能、可靠性和成本。

## 五种基本拓扑结构详解

### 1. 总线型拓扑

```
计算机1 ──── 计算机2 ──── 计算机3 ──── 计算机4
                         │
                       终端器
```

- **结构**：所有节点连接到一条共享总线上
- **通信方式**：任一时刻只允许一台设备发送数据
- **优点**：结构简单、布线容易、成本低
- **缺点**：总线故障导致全网瘫痪；故障隔离困难
- **应用**：早期的10Base-2以太网（已基本淘汰）

### 2. 星型拓扑 ⭐（最常用）

```
           计算机1
             │
   计算机2 ──交换机── 计算机3
             │
           计算机4
```

- **结构**：所有节点通过独立链路连接到中心设备（交换机/集线器）
- **优点**：单节点故障不影响其他节点；易于维护和扩展
- **缺点**：中心节点故障全网瘫痪；线缆用量大
- **应用**：**当前最常用的局域网拓扑**——学校机房、办公室网络

### 3. 环型拓扑

```
计算机1 ───→ 计算机2
   ↑              ↓
   计算机4 ←─── 计算机3
```

- **结构**：各节点首尾相连形成闭合环路，数据单向传输
- **优点**：无数据冲突，适合实时控制
- **缺点**：单节点故障全网瘫痪；扩展困难
- **应用**：令牌环网（Token Ring，已较少使用）

### 4. 树型拓扑

```
        根交换机
        │    │
   交换机1  交换机2
   │   │    │   │
  PC1 PC2  PC3 PC4
```

- **结构**：星型的层次化扩展，存在层级关系
- **优点**：易于扩展、分级管理
- **缺点**：上级节点故障影响下级
- **应用**：校园网、企业分支机构网络

### 5. 网状型拓扑

```
   计算机1 ═══ 计算机2
    ║  ║      ║  ║
   计算机3 ═══ 计算机4
```

- **结构**：节点之间多点连接，形成网状
- **优点**：可靠性极高、负载均衡
- **缺点**：成本高、布线复杂
- **应用**：Internet骨干网、军事通信

