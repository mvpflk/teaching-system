SET NAMES utf8mb4;

UPDATE exam_syllabus
SET content = '一、考试概述：本考纲依据教育部《中职英语课程标准（2020年版）》及《四川省对口升学考试大纲（2014年版）》制定。考查四大模块——词汇与语法约35%、阅读理解约30%、翻译约15%、写作约20%。难度：基础约60%/中等约30%/较难约10%。'
'二、词汇积累：高频核心300词(动词be/have/do/make/take,名词time/way/people,形容词good/big,介词in/on/at) + 考试核心500词(动词辨析spend/cost/take/pay,名词辨析chance/opportunity/ability,词组take care of/look forward to/be used to) + 考纲拓展词(阅读拓展词,写作常用词)。'
'三、语法专项(十大专题)：时态语态(一般现在时/过去时/将来时,进行时,完成时,被动语态)；非谓语动词(不定式to do,动名词V-ing,分词)；定语从句(that/which/who/when/where/why,非限制性)；名词性从句(宾语从句/主语从句/表语从句/同位语从句)；状语从句(时间/条件/原因/让步/目的)；主谓一致(语法一致/就近原则/意义一致)；情态动词(基本用法+推测用法)；虚拟语气(条件句虚拟)；情景交际(邀请/感谢/问路/建议)。'
'四、阅读理解(3-4篇短文,100-150词/篇)：细节理解题(直接定位+Wh-检索)；推理判断题(隐含意思推断)；主旨大意题(段落/全文概括)；词义猜测题(上下文推断)。'
'五、翻译：英译汉(关键词语理解+句式分析)；汉译英(基础词汇运用+基本句型构建)。'
'六、写作：应用文写作约80词(书信格式:称呼+正文+结束语+署名+日期；通知格式:标题+正文+单位+日期)；话题写作约80-100词(校园生活/家庭朋友/未来规划等,观点表达+逻辑衔接first/besides/however/therefore)。',
    version = '2.0', updated_at = NOW()
WHERE subject_id = (SELECT id FROM dict_subject WHERE subject_name = '英语[职高]' AND status = 1 LIMIT 1)
  AND exam_type = 'DUIKOU'
  AND title LIKE '%对口升学%英语%';

SELECT 'v142: Syllabus updated to 2.0' AS result;
