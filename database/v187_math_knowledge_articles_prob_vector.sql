'## 排列（有序）

从n个**不同**元素中取出m个，按**一定顺序**排成一列。

**排列数公式**：

**A(n,m) = n!/(n-m)! = n(n-1)(n-2)...(n-m+1)**

从n开始连乘m个递减的数。

**全排列**：A(n,n) = n!

**例**：A(5,2) = 5×4 = 20

## 组合（无序）

从n个**不同**元素中取出m个，**不考虑顺序**合成一组。

**组合数公式**：

**C(n,m) = n!/[m!(n-m)!] = A(n,m)/m!**

组合 = 排列 ÷ m!（去掉顺序的影响）

**例**：C(5,2) = 5×4/(2×1) = 10

## 核心区别

| | 排列 | 组合 |
|:--:|:----:|:----:|
| 顺序 | **看顺序** | **不看顺序** |
| 公式 | A(n,m) | C(n,m) |
| 关系 | — | C(n,m)=A(n,m)/m! |
| 示例 | AB≠BA | AB=BA |

