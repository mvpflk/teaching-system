'## 两大计数原理

### 分类加法原理（加法原理）

完成一件事有**n类不同方案**，第k类有mₖ种方法，则总数为：

**N = m₁ + m₂ + ... + mₙ**

> 关键词："或"——任选一类即可完成。

### 分步乘法原理（乘法原理）

完成一件事需要**n个步骤**，第k步有mₖ种方法，则总数为：

**N = m₁ × m₂ × ... × mₙ**

> 关键词："且"——每步都做才完成。

## 核心区分

| | 加法原理 | 乘法原理 |
|:--:|:--------:|:--------:|
| 关键词 | **或** | **且** |
| 方案关系 | 各类**独立**完成 | 各步**依次**完成 |
| 计算方法 | **相加** | **相乘** |
| 类比 | 走路：有3条路可选1条 | 穿衣：上衣+裤子都要选 |

## 典型例题

**例1**（加法原理）：从A到B有3条公路，2条铁路。选一种方式从A到B，有几种选法？

公路和铁路是两类独立方案，选一种即可。

N = 3 + 2 = **5** 种

**例2**（乘法原理）：有3件上衣、2条裤子、2双鞋。各选一件搭配，有几种穿法？

上衣、裤子、鞋是三个步骤，都要选。

N = 3 × 2 × 2 = **12** 种

**例3**（混合）：从A到B有3条路，从B到C有4条路。从A经B到C有几种走法？

