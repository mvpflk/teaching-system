/**
 * 知识文章内容视觉增强器
 *
 * 将知识库四段式【标签】格式转换为结构化 Markdown，提升阅读体验：
 * - 【标签】→ ### 标题（带 emoji 图标）
 * - ①②③ → 编号列表
 * - 检测已有 Markdown 标题，避免重复转换
 *
 * 参考：信息技术应用基础 / 网络应用基础 的文章格式风格
 * @since 2026-07-01
 */

/** 判断是否需要增强（是否为【标签】格式的纯文本内容） */
function needsEnhancement(md) {
  if (!md) return false;
  // 已有 Markdown 标题（#, ##, ###）的不重复处理
  if (/^#{1,3}\s/.test(md.trimStart())) return false;
  // 有【标签】的需要增强
  return /【[^】]+】/.test(md);
}

/** 主转换函数：纯文本 → 结构化 Markdown */
export function formatKnowledgeContent(md) {
  if (!needsEnhancement(md)) return md;

  let html = md;

  // ============================================================
  // 步骤1：标签 → 标题（带 emoji 图标，提升视觉区分度）
  // ============================================================
  const TAG_MAP = [
    [/【一句话定义】/g, '### 📖 一句话定义'],
    [/【具体说明】/g, '### 📝 具体说明'],
    [/【具体例子】/g, '### 📝 具体例子'],
    [/【常见错误】/g, '### ⚠️ 常见错误'],
    [/【考试方向】/g, '### 🎯 出题方向'],
    [/【出题方向】/g, '### 🎯 出题方向'],
    [/【即时自测】/g, '### ✏️ 即时自测'],
    [/【必背名句[·⋅·]上下句对照】/g, '### 📜 必背名句 · 上下句对照'],
    [/【理解性默写提示】/g, '### 💡 理解性默写提示'],
    [/【(.+?)·速查表】/g, '### 📊 $1 · 速查表'],
    [/【(.+?)】/g, '### 📌 $1'],
  ];

  for (const [pattern, replacement] of TAG_MAP) {
    html = html.replace(pattern, replacement);
  }

  // ============================================================
  // 步骤2：①②③ → 编号列表（Markdown 有序列表）
  // ============================================================
  html = html.replace(/[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮]/g, (match) => {
    const map = {
      '①': '1',
      '②': '2',
      '③': '3',
      '④': '4',
      '⑤': '5',
      '⑥': '6',
      '⑦': '7',
      '⑧': '8',
      '⑨': '9',
      '⑩': '10',
      '⑪': '11',
      '⑫': '12',
      '⑬': '13',
      '⑭': '14',
      '⑮': '15',
    };
    return '\n' + (map[match] || match) + '. ';
  });

  // ============================================================
  // 步骤3：内联标记增强
  // ============================================================

  // 错误标记 ✗ → 红色提示
  html = html.replace(/（[✗×]）/g, ' ❌ ');
  // 正确标记 ✓ → 绿色提示
  html = html.replace(/（[✓✔]）/g, ' ✅ ');

  // 易错字提示：把 "——易错字：" 后的内容变为引用块
  html = html.replace(/——(易错字[：:][^\n]+)/g, '\n> ⚡ $1');

  // ============================================================
  // 步骤4：段落呼吸（连续文本间增加空行）
  // ============================================================
  // 标题前加空行
  html = html.replace(/([^\n])\n(###\s)/g, '$1\n\n$2');
  // 标题后确保有空行
  html = html.replace(/(###\s[^\n]+)\n([^\n#])/g, '$1\n\n$2');

  // ============================================================
  // 步骤5：检测表格行（以 | 起始且含 | 分隔），不改动已存在的表格
  // ============================================================
  // （表格行已有 Markdown 格式原样保留，不做处理）

  return html;
}

/** 渲染增强后的 Markdown — 配合 renderMarkdown 使用 */
export function renderFormattedContent(md, renderMarkdownFn) {
  const formatted = formatKnowledgeContent(md);
  return renderMarkdownFn(formatted);
}
